import { existsSync } from "node:fs";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Regenerates the frontend's contract bindings from the compiled Hardhat artifact.
 *
 *   npm run compile && npm run export:abi
 *
 * It writes two files into the frontend workspace:
 *
 *   frontend/lib/abi/ProductProvenance.ts     the ABI as a `const` assertion, so
 *                                             viem / wagmi infer argument and
 *                                             return types for free
 *   frontend/lib/deployed-contracts.json      chainId -> contract address, built
 *                                             from `contracts/deployments/*.json`
 *
 * No network connection is required, so this works offline and in CI.
 */
const CONTRACT_NAME = "ProductProvenance";

const contractsRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const projectRoot = join(contractsRoot, "..");
const frontendLib = join(projectRoot, "frontend", "lib");

// ---------------------------------------------------------------------------
// 1. Locate the compiled artifact
// ---------------------------------------------------------------------------
async function findArtifact(dir: string, fileName: string): Promise<string | undefined> {
  if (!existsSync(dir)) return undefined;

  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      const nested = await findArtifact(fullPath, fileName);
      if (nested !== undefined) return nested;
    } else if (entry.name === fileName) {
      return fullPath;
    }
  }

  return undefined;
}

const artifactPath = await findArtifact(join(contractsRoot, "artifacts"), `${CONTRACT_NAME}.json`);
if (artifactPath === undefined) {
  throw new Error(`Could not find ${CONTRACT_NAME}.json in contracts/artifacts. Run \`npm run compile\` first.`);
}

const artifact = JSON.parse(await readFile(artifactPath, "utf8")) as { abi: unknown[] };

// ---------------------------------------------------------------------------
// 2. Write the ABI in two flavours
//    - a `.ts` module with a `const` assertion, so viem / wagmi infer argument
//      and return types
//    - a plain `.json` file, so ethers.js can consume it directly
// ---------------------------------------------------------------------------
const abiDir = join(frontendLib, "abi");
await mkdir(abiDir, { recursive: true });

const abiFile = join(abiDir, `${CONTRACT_NAME}.ts`);
const abiSource = `// AUTO-GENERATED by \`npm run export:abi\` in the contracts workspace.
// Do not edit by hand - regenerate it after changing the Solidity source.
export const productProvenanceAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
await writeFile(abiFile, abiSource, "utf8");
console.log(`ABI   -> frontend/lib/abi/${CONTRACT_NAME}.ts (${artifact.abi.length} entries)`);

const abiJsonFile = join(abiDir, `${CONTRACT_NAME}.json`);
await writeFile(abiJsonFile, `${JSON.stringify({ abi: artifact.abi }, null, 2)}\n`, "utf8");
console.log(`ABI   -> frontend/lib/abi/${CONTRACT_NAME}.json (ethers.js flavour)`);

// ---------------------------------------------------------------------------
// 3. Collect every recorded deployment into a chainId -> address map
// ---------------------------------------------------------------------------
type Deployment = { contract?: string; networkName: string; chainId: string; address: string };
const byChainId: Record<string, Deployment> = {};

const deploymentsDir = join(contractsRoot, "deployments");
if (existsSync(deploymentsDir)) {
  for (const file of await readdir(deploymentsDir)) {
    if (!file.endsWith(".json")) continue;

    const deployment = JSON.parse(await readFile(join(deploymentsDir, file), "utf8")) as Deployment;
    if (deployment.contract !== undefined && deployment.contract !== CONTRACT_NAME) continue;

    byChainId[deployment.chainId] = deployment;
  }
}

const addressFile = join(frontendLib, "deployed-contracts.json");
const addressMap = { [CONTRACT_NAME]: byChainId };
await writeFile(addressFile, `${JSON.stringify(addressMap, null, 2)}\n`, "utf8");

const chainIds = Object.keys(byChainId);
console.log(
  chainIds.length === 0
    ? "Addresses -> frontend/lib/deployed-contracts.json (no deployments recorded yet)"
    : `Addresses -> frontend/lib/deployed-contracts.json (chainIds: ${chainIds.join(", ")})`,
);
