"use client";

import { useQueryClient } from "@tanstack/react-query";
import { useEffect, useMemo } from "react";
import {
  useConnection,
  useReadContract,
  useReadContracts,
  useWaitForTransactionReceipt,
  useWriteContract,
} from "wagmi";

import {
  ROLE_HASH,
  ZERO_ADDRESS,
  getRegistryAddress,
  productWarrantyRegistryAbi as registryAbi,
  type OwnershipRecord,
  type ProductRecord,
  type RoleName,
  type ServiceRecord,
  type WarrantyClaimRecord,
} from "./contracts";

/**
 * Registry reads and writes shared by every console.
 *
 * All hooks are thin wrappers over wagmi, so they inherit the `const` ABI types
 * generated by `npm run export:abi`. `useRegistryWrite` also invalidates every
 * cached read after a confirmation, which keeps the open dashboards in sync after
 * a transfer or a claim.
 */

/** Address of the registry on the connected chain. */
export function useRegistryAddress(): `0x${string}` {
  const connection = useConnection();
  return getRegistryAddress(connection.chainId);
}

const ROLE_NAMES = Object.keys(ROLE_HASH) as RoleName[];

export type RoleState = {
  address?: `0x${string}`;
  isConnected: boolean;
  roles: Record<RoleName, boolean>;
  isLoading: boolean;
};

/** Which supply-chain roles the connected wallet holds. */
export function useRoles(): RoleState {
  const connection = useConnection();
  const address = connection.address;
  const registry = getRegistryAddress(connection.chainId);

  const query = useReadContracts({
    contracts: ROLE_NAMES.map((name) => ({
      address: registry,
      abi: registryAbi,
      functionName: "hasRole" as const,
      args: [ROLE_HASH[name], address ?? ZERO_ADDRESS],
    })),
    query: { enabled: address !== undefined },
  });

  const roles = ROLE_NAMES.reduce<Record<RoleName, boolean>>(
    (accumulator, name, index) => {
      accumulator[name] = query.data?.[index]?.result === true;
      return accumulator;
    },
    { admin: false, manufacturer: false, retailer: false, customer: false, serviceCenter: false },
  );

  return { address, isConnected: connection.isConnected, roles, isLoading: query.isLoading };
}

/** Number of registered units (ids run 1..total). */
export function useTotalProducts() {
  const registry = useRegistryAddress();
  const query = useReadContract({ address: registry, abi: registryAbi, functionName: "totalProducts" });

  return {
    total: typeof query.data === "bigint" ? query.data : 0n,
    isLoading: query.isLoading,
    error: query.error,
  };
}

export type ProductRow = {
  id: bigint;
  product: ProductRecord;
  /** Canonical, clock-derived warranty status (see `getWarrantyStatus`). */
  warrantyStatus: number;
};

/**
 * Every registered unit together with its derived warranty status.
 *
 * The registry exposes no enumerable list, so the ids 1..totalProducts() are read
 * in two batched multicalls. That is fine for a course-sized registry; a real
 * deployment would index the `ProductRegistered` event instead.
 */
export function useProductList() {
  const registry = useRegistryAddress();
  const { total, isLoading: isLoadingCount } = useTotalProducts();

  const ids = useMemo(() => {
    const count = Number(total);
    return Array.from({ length: Number.isFinite(count) ? count : 0 }, (_, index) => BigInt(index + 1));
  }, [total]);

  const products = useReadContracts({
    contracts: ids.map((id) => ({
      address: registry,
      abi: registryAbi,
      functionName: "getProduct" as const,
      args: [id],
    })),
    query: { enabled: ids.length > 0 },
  });

  const statuses = useReadContracts({
    contracts: ids.map((id) => ({
      address: registry,
      abi: registryAbi,
      functionName: "getWarrantyStatus" as const,
      args: [id],
    })),
    query: { enabled: ids.length > 0 },
  });

  const rows = useMemo<ProductRow[]>(() => {
    return ids.flatMap((id, index) => {
      const entry = products.data?.[index];
      if (entry === undefined || entry.status !== "success") return [];

      const statusEntry = statuses.data?.[index];
      const warrantyStatus = statusEntry?.status === "success" ? Number(statusEntry.result) : 0;

      return [{ id, product: entry.result as unknown as ProductRecord, warrantyStatus }];
    });
  }, [ids, products.data, statuses.data]);

  return { rows, total, isLoading: isLoadingCount || products.isLoading };
}

/** Everything the detail views need for one unit. */
export function useProductDetail(productId?: bigint) {
  const registry = useRegistryAddress();
  const enabled = productId !== undefined && productId > 0n;
  const args = [productId ?? 0n] as const;

  const product = useReadContract({
    address: registry,
    abi: registryAbi,
    functionName: "getProduct",
    args,
    query: { enabled },
  });

  const history = useReadContract({
    address: registry,
    abi: registryAbi,
    functionName: "getOwnershipHistory",
    args,
    query: { enabled },
  });

  const claims = useReadContract({
    address: registry,
    abi: registryAbi,
    functionName: "getWarrantyClaims",
    args,
    query: { enabled },
  });

  const serviceLog = useReadContract({
    address: registry,
    abi: registryAbi,
    functionName: "getServiceLog",
    args,
    query: { enabled },
  });

  const warrantyStatus = useReadContract({
    address: registry,
    abi: registryAbi,
    functionName: "getWarrantyStatus",
    args,
    query: { enabled },
  });

  const remainingClaims = useReadContract({
    address: registry,
    abi: registryAbi,
    functionName: "remainingClaims",
    args,
    query: { enabled },
  });

  return {
    product: product.data as unknown as ProductRecord | undefined,
    history: (history.data as unknown as OwnershipRecord[] | undefined) ?? [],
    claims: (claims.data as unknown as WarrantyClaimRecord[] | undefined) ?? [],
    serviceLog: (serviceLog.data as unknown as ServiceRecord[] | undefined) ?? [],
    warrantyStatus: warrantyStatus.data === undefined ? 0 : Number(warrantyStatus.data),
    remainingClaims: (remainingClaims.data as bigint | undefined) ?? 0n,
    isLoading: product.isLoading,
    error: product.error,
  };
}

/**
 * Write helper: submits a transaction, tracks its receipt and refreshes every
 * cached read once it is mined, so the consoles update without a manual reload.
 */
export function useRegistryWrite() {
  const queryClient = useQueryClient();
  const { mutate, data: hash, isPending, error: writeError, reset } = useWriteContract();
  const receipt = useWaitForTransactionReceipt({ hash });

  useEffect(() => {
    if (receipt.isSuccess) {
      void queryClient.invalidateQueries();
    }
  }, [receipt.isSuccess, queryClient]);

  return {
    write: mutate,
    hash,
    isPending,
    isConfirming: receipt.isLoading,
    isSuccess: receipt.isSuccess,
    error: writeError ?? receipt.error ?? undefined,
    reset,
  };
}
